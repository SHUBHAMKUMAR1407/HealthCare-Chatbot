import os
import nltk
import random
import numpy as np
import json
import pickle
from nltk.stem import WordNetLemmatizer
from tensorflow.keras.models import load_model

BASE_DIR = os.path.dirname(os.path.abspath(__file__))
lemmatizer=WordNetLemmatizer()

def ensure_nltk_data():
  resources = [
    ('punkt', 'tokenizers/punkt'),
    ('punkt_tab', 'tokenizers/punkt_tab'),
    ('wordnet', 'corpora/wordnet'),
    ('omw-1.4', 'corpora/omw-1.4'),
  ]
  for package, path in resources:
    try:
      nltk.data.find(path)
    except LookupError:
      nltk.download(package, quiet=True)

ensure_nltk_data()

with open(os.path.join(BASE_DIR, 'intents.json'), encoding='utf-8') as json_file:
    intents = json.load(json_file)

words=pickle.load(open(os.path.join(BASE_DIR, 'words.pkl'),'rb'))
classes=pickle.load(open(os.path.join(BASE_DIR, 'classes.pkl'),'rb'))
model=load_model(os.path.join(BASE_DIR, 'chatbotmodel.h5'), compile=False)

def clean_up_sentence(sentence):
  sentence_words=nltk.word_tokenize(sentence)
  sentence_words=[lemmatizer.lemmatize(word) for word in sentence_words]
  return sentence_words

def bag_of_words(sentence):
  sentence_words=clean_up_sentence(sentence)
  bag=[0]*len(words)
  for w in sentence_words:
    for i,word in enumerate(words):
      if word == w:
        bag[i]=1
  return np.array(bag)

def predict_class(sentence):
  bow=bag_of_words(sentence)
  res=model.predict(np.array([bow]), verbose=0)[0]
  ERROR_THRESHOLD=0.25
  results=[[i,r] for i,r in enumerate(res) if r> ERROR_THRESHOLD]

  results.sort(key=lambda x:x[1],reverse=True)
  return_list=[]
  for r in results:
    return_list.append({'intent': classes[r[0]],'probability':str(r[1])})
  return return_list

def get_response(intents_list,intents_json):
  if not intents_list:
    return None
  tag=intents_list[0]['intent']
  list_of_intents=intents_json['intents']
  for i in list_of_intents:
    if i['tag']==tag:
      return random.choice(i['responses'])
  return None

STOP_WORDS = {
  'a', 'an', 'and', 'are', 'as', 'at', 'be', 'can', 'do', 'does', 'for',
  'from', 'have', 'has', 'how', 'i', 'if', 'in', 'is', 'it', 'me', 'my',
  'of', 'on', 'or', 'should', 'some', 'tell', 'that', 'the', 'there', 'this',
  'to', 'was', 'what', 'when', 'who', 'why', 'will', 'with', 'you', 'your',
  'am', 'get', 'got', 'suffering',
}

def content_words(text):
  return set(
    word.lower() for word in clean_up_sentence(text)
    if word.isalnum() and word.lower() not in STOP_WORDS
  )

def match_intent_by_pattern(sentence):
  sentence_words=content_words(sentence)
  if not sentence_words:
    return None
  best_tag=None
  best_score=0.0
  for intent in intents['intents']:
    for pattern in intent['patterns']:
      pattern_words=content_words(pattern)
      if not pattern_words:
        continue
      overlap=len(sentence_words & pattern_words)
      if overlap == 0:
        continue
      score=2 * overlap / (len(sentence_words) + len(pattern_words))
      if pattern.lower() in sentence.lower():
        score=1.0
      if score > best_score:
        best_score=score
        best_tag=intent['tag']
  if best_score >= 0.5:
    return best_tag
  return None

def chat(message):
  message=(message or "").strip()
  if not message:
    return "Please type a message."

  pattern_tag=match_intent_by_pattern(message)
  if pattern_tag:
    res=get_response([{'intent': pattern_tag}],intents)
    if res:
      return res

  ints=predict_class(message)
  res=get_response(ints,intents)
  if res:
    return res

  return "Sorry, I didn't get that."

if __name__ == "__main__":
  print("GO! BOT IS RUNNING")
  while True:
    message=input("")
    print(chat(message))